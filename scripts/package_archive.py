#!/usr/bin/env python3
"""Package an expanded scientific source tree with a new checked archive identity."""
from pathlib import Path
import argparse
import hashlib
import json
import re
import tempfile
import zipfile

def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Expanded package directory')
    parser.add_argument('--parts', type=Path, required=True, help='Output artifact_parts directory')
    args = parser.parse_args()
    source = args.source.resolve()
    version = (source / 'VERSION').read_text().strip()
    if source.name != 'recomb2027-atlas' or not re.fullmatch(r'\d+\.\d+\.\d+', version):
        raise ValueError('Unexpected package name or version')
    files = sorted(p for p in source.rglob('*') if p.is_file())
    if any(p.is_symlink() for p in source.rglob('*')):
        raise ValueError('The source tree must not contain symbolic links')
    if any('__pycache__' in p.parts or p.suffix in {'.pyc', '.pyo'} for p in files):
        raise ValueError('Remove generated bytecode before packaging')
    manifest = source / 'SHA256SUMS.txt'
    manifest.write_text(''.join(f'{sha(p)}  {p.relative_to(source).as_posix()}\n'
                                for p in files if p != manifest))
    files = sorted(set(files) | {manifest})
    args.parts.mkdir(parents=True, exist_ok=True)
    archive_name = f'GeoCert_RECOMB_{version}_Source.zip'
    with tempfile.TemporaryDirectory() as temporary:
        archive = Path(temporary) / archive_name
        with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as out:
            for path in files:
                info = zipfile.ZipInfo(source.name + '/' + path.relative_to(source).as_posix(), (2000, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (0o100644 << 16)
                out.writestr(info, path.read_bytes(), compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
        parts = []
        with archive.open('rb') as stream:
            index = 0
            while block := stream.read(4 * 1024 * 1024):
                name = f'part{index:03d}'
                (args.parts / name).write_bytes(block)
                parts.append({'name': name, 'sha256': hashlib.sha256(block).hexdigest(), 'size': len(block)})
                index += 1
        wanted = {item['name'] for item in parts}
        for path in args.parts.glob('part[0-9][0-9][0-9]'):
            if path.name not in wanted:
                path.unlink()
        record = {'archive': archive_name, 'root': source.name, 'distribution_version': version,
                  'sha256': sha(archive), 'size': archive.stat().st_size, 'parts': parts}
        (args.parts / 'manifest.json').write_text(json.dumps(record, indent=2) + '\n')
    (args.parts.parent / 'ARCHIVE_SHA256SUMS.txt').write_bytes(manifest.read_bytes())
    print(json.dumps({'version': version, 'files': len(files), 'archive_sha256': record['sha256'],
                      'size': record['size'], 'parts': len(parts)}))

if __name__ == '__main__':
    main()
